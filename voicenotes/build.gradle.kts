plugins {
    // Android LIBRARY (not application): no applicationId, no versionName, no Compose. Mirrors
    // :recorder's shape (REC-05 rework) — this is the THIRD standalone, publishable library module
    // (Phase 10, plan 10-03), composing :recorder for capture and adding a Room-backed persisted
    // note queue + WorkManager-driven drain.
    alias(libs.plugins.android.library)
    alias(libs.plugins.kotlin.android)
    // Same rationale as :stt/:recorder (D-12): freezes this module's own public surface. Provides
    // :voicenotes:apiDump / :voicenotes:apiCheck.
    alias(libs.plugins.binary.compatibility.validator)
    // Room's KSP2 annotation-processing engine — first usage of KSP in this codebase (D-03).
    alias(libs.plugins.ksp)
    `maven-publish`
}

android {
    // A distinct AGP namespace string from :stt's/:recorder's — AGP namespaces need only be unique
    // strings, not hierarchically related to the Kotlin package names below.
    namespace = "io.github.ygaray.sttengine.voicenotes"
    compileSdk = 36

    defaultConfig {
        minSdk = 33
        // No targetSdk / applicationId — a library inherits the consuming app's targetSdk.

        consumerProguardFiles("consumer-rules.pro")
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    testOptions {
        // Robolectric needs merged Android resources on the unit-test classpath for NoteDaoTest's
        // Room-on-JVM suite (mirrors :recorder's testOptions — the D-19 web-parity unitTests.all
        // block is deliberately OMITTED: that machinery belongs exclusively to :stt's frozen
        // recognition-contract concern, which has nothing to do with note persistence).
        unitTests.isIncludeAndroidResources = true
        // Un-stubbed android.jar methods return a default instead of throwing, so a pure-JVM test
        // can touch the platform surface without a Robolectric runtime.
        unitTests.isReturnDefaultValues = true
    }

    // AGP-8 opt-in: declare the single publishable variant + its sources jar. MANDATORY —
    // without this, `from(components["release"])` below fails ("'release' property cannot be
    // found"), the #1 JitPack-Android publish failure.
    publishing {
        singleVariant("release") {
            withSourcesJar()
        }
    }
}

// ---------------------------------------------------------------------------------------------
// THE API FREEZE (mirrors :stt's/:recorder's, D-12).
//
// `api/voicenotes.api` is a golden dump of this module's RELEASE compilation, generated by
// :voicenotes:apiDump and diffed by :voicenotes:apiCheck. Any change to a public signature fails
// the build with a diff naming the symbol, instead of passing review unnoticed.
//
// Do NOT migrate to Kotlin's built-in `abiValidation` extension — see :stt/build.gradle.kts's
// comment for the full rationale (it explicitly excludes Android library projects and would
// configure nothing while the check still reported green).
//
// The plugin already makes `check` depend on `apiCheck`. This declaration is deliberately explicit
// and redundant, same rationale as :stt/:recorder: it makes the wiring load-bearing IN THIS FILE
// rather than an inherited plugin default.
tasks.named("check") {
    dependsOn(tasks.named("apiCheck"))
}

// TOP-LEVEL kotlin { } — a SIBLING of android { }, deliberately NOT nested inside it (mirrors
// :stt's/:recorder's Pitfall-9 warning: AGP's KotlinAndroidProjectExtension is a different
// receiver, and explicitApi() nested inside android {} would not do what is intended).
kotlin {
    explicitApi()
    compilerOptions {
        jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17)
    }
}

// NoteDatabase declares `exportSchema = true` (D-03: migration-safe from day one, no
// fallbackToDestructiveMigration()) — that flag is inert without telling KSP where to write the
// schema JSON, which is what makes an actual future Migration checkable against version 1's real
// shape. Without this arg, Room silently skips the export and only warns at compile time.
ksp {
    arg("room.schemaLocation", "$projectDir/schemas")
}

dependencies {
    // Flow/StateFlow on the public surface — same D-07-derived rationale as :stt/:recorder.
    api(libs.coroutines.android)

    // Composes the Recorder for capture — NEVER project(":stt"). This module has zero recognition
    // dependency, mirroring the "server-only, never native" phase note (mirrors :recorder's own
    // module-boundary precedent, in the opposite direction: a NEW consumer of :recorder).
    implementation(project(":recorder"))

    // Plan 10-04's DrainWorker multipart upload. `implementation`, not `api`: no OkHttp type may
    // reach the public VoiceNotes surface, mirrors :stt's Phase-9 OkHttp scoping.
    implementation(libs.okhttp)

    // Room-backed persisted note queue (D-03, first Room usage in this codebase).
    implementation(libs.room.runtime)
    implementation(libs.room.ktx)
    ksp(libs.room.compiler)

    // WorkManager-driven background drain, surviving app close (NOTE-05).
    implementation(libs.work.runtime.ktx)

    // JVM unit tests — NoteDaoTest.kt is Robolectric-only (mirrors RecorderTest's convention).
    testImplementation(libs.junit)
    testImplementation(libs.coroutines.test)
    testImplementation(libs.robolectric)
    testImplementation(libs.androidx.test.core)
    testImplementation(libs.work.testing)
}

// JitPack android-example publishing form, mirrors :stt's/:recorder's exactly. `from(components["release"])`
// MUST be inside afterEvaluate — the "release" software component does not exist at configuration
// time (it is created by the AGP singleVariant("release") opt-in above).
publishing {
    publications {
        register<MavenPublication>("release") {
            groupId = "com.github.Ygaray"
            // == the MIRROR REPO NAME's third published artifact, not the module name (:voicenotes).
            // Mirrors the sibling naming convention (module :recorder -> artifact
            // voice-engine-android-recorder): module :voicenotes -> artifact
            // voice-engine-android-voicenotes.
            artifactId = "voice-engine-android-voicenotes"
            version = "0.6.0"
            afterEvaluate {
                from(components["release"])
            }
        }
    }
}
