    // into its own module so it structurally never depends on recognition code.
    alias(libs.plugins.android.library)
    alias(libs.plugins.kotlin.android)
    // Same rationale as :stt (D-12): freezes this module's own public surface. Provides
    // :recorder:apiDump / :recorder:apiCheck.
