// verifyNoRecognitionDependency (T-08-10) — THE PRIMARY REC-05 structural proof.
//
// Inspects the RESOLVED dependency graph of this module's own release configurations — not just
// this file's source text (that's check-no-recognition-dependency.sh's job, a fast static
// pre-flight belt-and-suspenders layer) — and fails loudly if :stt (or its published coordinate)
// is anywhere in it. Wired into `check`, so every `./gradlew :recorder:check` re-proves the
// boundary automatically: a future edit that re-adds `implementation(project(":stt"))` here fails
// by name, not by a reviewer remembering a rule.
//
// The inspection logic lives inside doLast {} (execution time), not directly in the registration
// block (configuration time): resolutionResult over releaseRuntimeClasspath/
// releaseCompileClasspath can throw or behave inconsistently before AGP has fully configured all
// release variants, which only happens by execution time.
tasks.register("verifyNoRecognitionDependency") {
    group = "verification"
    description = "Fails if :recorder's resolved release classpath ever names :stt (T-08-10, REC-05)."

    doLast {
        // WR-02: release-only scope is DELIBERATE, not an oversight — only the release variant is
        // ever published (see `publishing { singleVariant("release") }` above), so that is the only
        // classpath this compile-time guarantee needs to cover. A `debugImplementation(project(":stt"))`
        // would not be caught here, but it also never reaches the published artifact, so it cannot
        // break REC-05's actual guarantee for consumers.
        val configurationsToCheck = listOf("releaseRuntimeClasspath", "releaseCompileClasspath")
        val forbiddenProjectPath = ":stt"
        val forbiddenModuleName = "voice-engine-android"
        // Vacuous-pass-prevention target (mirrors ReleaseAudioSourceSeamTest / check-r8-mapping.sh's
        // discipline): assert the SAME resolved set genuinely contains something expected BEFORE
        // asserting the absence of something forbidden.
        // IN-02: update this if :recorder's dependency set ever changes — this check hard-codes
        // coroutines-android as the "something expected" and would start failing check for an
        // unrelated reason if that dependency is ever swapped or renamed upstream.
        val expectedModuleName = "kotlinx-coroutines-android"

        for (configurationName in configurationsToCheck) {
            val configuration = configurations.findByName(configurationName)
                ?: throw org.gradle.api.GradleException(
                    "verifyNoRecognitionDependency: configuration '$configurationName' does not " +
                        "exist on :recorder. This check proves nothing without a real resolved " +
                        "configuration to inspect.",
                )

            val resolutionResult = configuration.incoming.resolutionResult
            val allComponents = resolutionResult.allComponents

            val expectedFound = allComponents.any { component ->
                val id = component.id
                id is org.gradle.api.artifacts.component.ModuleComponentIdentifier &&
                    id.module == expectedModuleName
            }
            if (!expectedFound) {
                throw org.gradle.api.GradleException(
                    "verifyNoRecognitionDependency: resolved configuration '$configurationName' " +
                        "does not contain '$expectedModuleName'. The resolved configuration is " +
                        "empty, came from the wrong task, or resolution failed — this check proves " +
                        "nothing on an empty/broken resolution. Found components: " +
                        allComponents.joinToString { it.id.toString() },
                )
            }

            for (component in allComponents) {
                val id = component.id
                val isForbiddenProject = id is org.gradle.api.artifacts.component.ProjectComponentIdentifier &&
                    id.projectPath == forbiddenProjectPath
                val isForbiddenModule = id is org.gradle.api.artifacts.component.ModuleComponentIdentifier &&
                    id.module == forbiddenModuleName

                if (isForbiddenProject || isForbiddenModule) {
                    throw org.gradle.api.GradleException(
                        "verifyNoRecognitionDependency: FAIL — configuration '$configurationName' " +
                            "resolves a dependency on '$forbiddenProjectPath' (found: ${id}). " +
                            ":recorder must NEVER depend on :stt or its published coordinate " +
                            "(T-08-10, REC-05) — this is the compile-time module-boundary guarantee " +
                            "this whole module exists to provide.",
                    )
                }
            }
        }
    }
}

tasks.named("check") {
    dependsOn("verifyNoRecognitionDependency")
}
