    // A distinct AGP namespace string from :stt's ("io.github.ygaray.sttengine") — AGP namespaces
    // need only be unique strings, not hierarchically related to the Kotlin package names below,
    // which stay byte-for-byte identical to their original :stt home (plan 08-05 is a pure
    // module-boundary move, not a rename).
    namespace = "io.github.ygaray.sttengine.recorder"
    compileSdk = 36

    defaultConfig {
        minSdk = 33
        // No targetSdk / applicationId — a library inherits the consuming app's targetSdk.

        consumerProguardFiles("consumer-rules.pro")
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    testOptions {
        // Robolectric needs merged Android resources on the unit-test classpath for RecorderTest's
        // platform-adapter suite (mirrors :stt's testOptions — the D-19 web-parity unitTests.all
