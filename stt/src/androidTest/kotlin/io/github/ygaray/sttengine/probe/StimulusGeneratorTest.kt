package io.github.ygaray.sttengine.probe

import android.speech.tts.TextToSpeech
import android.speech.tts.UtteranceProgressListener
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File
import java.util.Locale
import java.util.concurrent.CountDownLatch
import java.util.concurrent.TimeUnit

/**
 * Regenerates the committed probe stimulus. **Opt-in — it is a tool, not a test**, and it is skipped
 * (via `assumeTrue`) unless explicitly asked for, so a plain `connectedDebugAndroidTest` in any
 * later plan never runs it.
 *
 * The host has no TTS binary at all (no espeak / pico2wave / festival / flite), so the only speech
 * synthesiser in this system is the one already on the tester — Google TTS, which the part-1 probe
 * incidentally proved is installed and is in fact the package backing recognition
 * (`com.google.android.tts`). Synthesising *on* the device is therefore not a workaround; it is the
 * only available source of real read speech, and it has the pleasant property that the stimulus is
 * generated by the same vendor stack that will consume it.
 *
 * This emits **one WAV per utterance** rather than one long file, deliberately: `TextToSpeech` will
 * not insert the multi-second inter-utterance pauses that
 * [ProbeStimulus.GAP_MS] requires, and those pauses are the entire basis of the
 * `EXTRA_SEGMENTED_SESSION` discriminator. The host stitches the parts together with exact digital
 * silence and resamples to 16 kHz mono — see the three-step procedure below.
 *
 * ### Regeneration procedure
 *
 * ```
 * # 1. synthesise the parts on the tester (note BOTH plan-01 invocation fixes)
 * cd android && ANDROID_SERIAL=<serial> ./gradlew :stt:connectedDebugAndroidTest \
 *   -Pandroid.testInstrumentationRunnerArguments.class=io.github.ygaray.sttengine.probe.StimulusGeneratorTest \
 *   -Pandroid.testInstrumentationRunnerArguments.generateStimulus=true \
 *   -Pandroid.injected.androidTest.leaveApksInstalledAfterRun=true
 *
 * # 2. pull them IMMEDIATELY — connectedAndroidTest deletes the app's external files dir on teardown
 * adb -s <serial> pull \
 *   /sdcard/Android/data/io.github.ygaray.sttengine.test/files/stimulus-parts <dest>
 *
 * # 3. stitch + resample on the host (the .py deliberately lives OUTSIDE assets/, which is
 * #    packaged verbatim into the test APK)
 * python3 android/scripts/build-stimulus.py <dest> \
 *   android/stt/src/androidTest/assets/probe-stimulus-16k-mono.wav
 * ```
 */
@RunWith(AndroidJUnit4::class)
class StimulusGeneratorTest {

    @Test
    fun synthesiseStimulusParts() {
        val args = InstrumentationRegistry.getArguments()
        // A tool, not a test: no-op unless explicitly requested. assumeTrue rather than @Ignore
        // because @Ignore cannot be overridden from the command line, and this must stay runnable.
        assumeTrue(
            "StimulusGeneratorTest is opt-in; pass -Pandroid.testInstrumentationRunner" +
                "Arguments.generateStimulus=true to regenerate the probe stimulus.",
            args.getString("generateStimulus") == "true",
        )

        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val outDir = File(
            requireNotNull(context.getExternalFilesDir(null)) {
                "external files dir unavailable — cannot write the stimulus parts"
            },
            "stimulus-parts",
        )
        outDir.deleteRecursively()
        check(outDir.mkdirs()) { "could not create ${outDir.absolutePath}" }

        var tts: TextToSpeech? = null
        try {
            val initStatus = CountDownLatch(1)
            var status = TextToSpeech.ERROR
            // Pin the engine rather than trusting the default: `settings get secure
            // tts_default_synth` is null on this device, so the default is resolved by the
            // framework and could differ between runs. A stimulus that silently changes voice
            // between regenerations would make similarity scores incomparable across probes.
            tts = TextToSpeech(
                context,
                { s ->
                    status = s
                    initStatus.countDown()
                },
                GOOGLE_TTS_PACKAGE,
            )
            assertTrue(
                "TextToSpeech did not initialise within $INIT_TIMEOUT_SECONDS s",
                initStatus.await(INIT_TIMEOUT_SECONDS, TimeUnit.SECONDS),
            )
            assertTrue("TextToSpeech init returned $status", status == TextToSpeech.SUCCESS)

            val engine = requireNotNull(tts)
            val langResult = engine.setLanguage(Locale.US)
            assertTrue(
                "en-US is not available to the TTS engine (setLanguage returned $langResult)",
                langResult >= TextToSpeech.LANG_AVAILABLE,
            )
            engine.setSpeechRate(1.0f)
            engine.setPitch(1.0f)

            val done = CountDownLatch(ProbeStimulus.UTTERANCES.size)
            val failures = mutableListOf<String>()
            engine.setOnUtteranceProgressListener(
                object : UtteranceProgressListener() {
                    override fun onStart(utteranceId: String?) = Unit

                    override fun onDone(utteranceId: String?) {
                        done.countDown()
                    }

                    @Deprecated("required override", ReplaceWith(""))
                    override fun onError(utteranceId: String?) {
                        synchronized(failures) { failures += "$utteranceId: unspecified error" }
                        done.countDown()
                    }

                    override fun onError(utteranceId: String?, errorCode: Int) {
                        synchronized(failures) { failures += "$utteranceId: code $errorCode" }
                        done.countDown()
                    }
                },
            )

            ProbeStimulus.UTTERANCES.forEachIndexed { index, text ->
                val id = "utt-%02d".format(index)
                val result = engine.synthesizeToFile(
                    text,
                    /* params = */ null,
                    File(outDir, "$id.wav"),
                    id,
                )
                assertTrue("synthesizeToFile queueing failed for $id", result == TextToSpeech.SUCCESS)
            }

            assertTrue(
                "synthesis did not complete within $SYNTH_TIMEOUT_SECONDS s",
                done.await(SYNTH_TIMEOUT_SECONDS, TimeUnit.SECONDS),
            )
            assertTrue("synthesis errors: $failures", failures.isEmpty())

            val written = outDir.listFiles()?.filter { it.length() > MIN_PART_BYTES }.orEmpty()
            assertTrue(
                "expected ${ProbeStimulus.UTTERANCES.size} non-trivial parts, got " +
                    "${written.size} in ${outDir.absolutePath}",
                written.size == ProbeStimulus.UTTERANCES.size,
            )
        } finally {
            tts?.let {
                it.stop()
                it.shutdown()
            }
        }
    }

    private companion object {
        const val GOOGLE_TTS_PACKAGE = "com.google.android.tts"
        const val INIT_TIMEOUT_SECONDS = 30L
        const val SYNTH_TIMEOUT_SECONDS = 180L

        /** A valid part is real audio; a bare 44-byte RIFF header is a silent failure. */
        const val MIN_PART_BYTES = 2_000L
    }
}
