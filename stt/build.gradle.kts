        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    testOptions {
        // Robolectric needs merged Android resources on the unit-test classpath for the thin
        // platform-adapter suite.
        unitTests.isIncludeAndroidResources = true
        // Un-stubbed android.jar methods return a default instead of throwing, so a pure-JVM test
        // can touch the platform surface without a Robolectric runtime.
        unitTests.isReturnDefaultValues = true

        // D-19 parity wiring — ErrorCodeParityTest reads both of these (Obstacle 1, resolution A).
        unitTests.all { test ->
            // rootProject.projectDir is <repo>/android in the mono-repo and the mirror root in the
            // public mirror, where ../web/src/errors.ts therefore does NOT exist — which is the
            // whole reason the test carries a skip. Passing an absolute path rather than letting
            // the test resolve one relative to its working directory removes every CWD-dependent
            // failure mode: the working directory of a Gradle test JVM is not a stable contract.
            //
            // Overridable by -Pstt.web.errorsTs=<path> so the guard's OWN failure modes stay
            // verifiable from the command line — pointing it at a non-existent path must skip by
            // default and hard-fail under -Pstt.requireWebParity=true. The override cannot be used
            // to dodge the gate: a bogus path in hard mode fails, and the repo-root three-way
            // script has no override at all.
            test.systemProperty(
                "stt.web.errorsTs",
                (
                    project.findProperty("stt.web.errorsTs")
                        ?: rootProject.file("../web/src/errors.ts").absolutePath
                    ).toString(),
            )
            // Flips that skip into a hard failure. Plan 12's release-android.sh ALWAYS passes
            // -Pstt.requireWebParity=true, so a release can never be tagged off a parity check
            // that silently did not run (threat T-05-08).
            test.systemProperty(
                "stt.requireWebParity",
                (project.findProperty("stt.requireWebParity") ?: "false").toString(),
            )
        }
    }

    // AGP-8 opt-in: declare the single publishable variant + its sources jar. MANDATORY —
    // without this, `from(components["release"])` below fails ("'release' property cannot be
    // found"), the #1 JitPack-Android publish failure.
    publishing {
        singleVariant("release") {
            withSourcesJar()
        }
    }
}

// ---------------------------------------------------------------------------------------------
// THE API FREEZE (plan 11, D-12).
//
// `api/stt.api` is a golden dump of the module's RELEASE compilation, generated by
// :stt:apiDump and diffed by :stt:apiCheck. Any change to a public signature — added member,
// changed parameter type, widened return — fails the build with a diff naming the symbol, instead
// of passing review unnoticed. That is the only mechanical control over what published consumers
// become dependent on (threat T-05-08).
//
// WHY THE STANDALONE VALIDATOR, NOT KOTLIN'S BUILT-IN `abiValidation`:
// Kotlin 2.2+ ships an experimental built-in ABI-validation extension, and it is the obvious thing
// for a future contributor to "upgrade" to. Do NOT. It operates on the JVM/KLib artifacts a plain
// Kotlin project publishes and explicitly does NOT apply to Android library projects, which
// publish an AAR. Applied here it would configure nothing and report nothing — the check would
// still be green, and it would have stopped checking. A guard that silently stops guarding is
// worse than no guard, because it converts an unverified surface into a documented-as-verified
// one. The standalone `binary-compatibility-validator` 0.18.1 is in maintenance mode; that is
// acceptable for a plugin whose entire job is to diff a text file, and it is the only option that
// configures the Android release compilation.
//
// The plugin already makes `check` depend on `apiCheck`. This declaration is deliberately explicit
// and redundant: it makes the wiring load-bearing IN THIS FILE rather than an inherited plugin
// default, so a plugin upgrade that quietly drops the hook fails here instead of silently
// unfreezing the surface. `dependsOn` is idempotent, so stating it twice costs nothing.
tasks.named("check") {
    dependsOn(tasks.named("apiCheck"))
}

// TOP-LEVEL kotlin { } — a SIBLING of android { }, deliberately NOT nested inside it (Pitfall 9).
// The sibling backup-engine nests `kotlin { compilerOptions { … } }` inside android { }; that is
// AGP's KotlinAndroidProjectExtension, a different receiver, and explicitApi() there would not do
// what is intended. explicitApi() is what makes the frozen stt.api dump meaningful (D-12).
kotlin {
    explicitApi()
    compilerOptions {
        jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17)
    }
}

dependencies {
    // The SOLE runtime dependency (D-09). Dispatchers.Main.immediate — required so a recognizer
    // callback already on the main looper is handled without a re-post — lives in the -android
    // artifact, not -core. No Hilt: this library has one construction path and no graph, and Hilt
    // would be a transitive burden on every consumer. No androidx.core either:
    // Context.checkSelfPermission is API 23+ and free (D-11 — the HOST requests the permission).
    //
    // `api`, NOT `implementation` (plan 02). Coroutines types are part of the PUBLIC SIGNATURE:
    // every member of the SttEngine interface is a Flow or StateFlow (D-07). With `implementation`
    // the generated POM scopes coroutines `runtime`, so a consumer resolving the published AAR gets
    // no kotlinx.coroutines on its COMPILE classpath and cannot so much as name `engine.state`'s
    // type — the library would publish successfully and then fail to compile against. `api` puts it
    // at `compile` scope, which is what an exported type requires.
    api(libs.coroutines.android)

    // Phase 9 (D-02): the ServerBackend's WS transport. `implementation`, NOT `api` — no OkHttp
    // type may ever reach the public SttEngine surface (mirrors the RecognizerHandle-seam
    // precedent); consumers must not need OkHttp on their compile classpath to use this library.
    implementation(libs.okhttp)

    // JVM unit tests — the majority of the suite runs here, behind the injected RecognizerHandle
    // seam, with no device and no Robolectric.
    testImplementation(libs.junit)
    testImplementation(libs.coroutines.test)
    // Robolectric — JVM host runner for the thin platform adapter only.
    testImplementation(libs.robolectric)
    testImplementation(libs.androidx.test.core)

    // Instrumented tests — the D-04 capability probe (RecognizerCapabilityProbeTest) is the reason
    // these exist; it can only be answered by the real recognizer service on the real device.
    androidTestImplementation(libs.androidx.test.junit)
    androidTestImplementation(libs.androidx.test.runner)
    // GrantPermissionRule — the probe runs unattended, so it grants RECORD_AUDIO itself rather than
    // relying on a host Activity (D-11) that an instrumented run does not have.
    androidTestImplementation(libs.androidx.test.rules)
    // Phase 9 Plan 03 (D-03/D-05): ServerHandoffProbeTest drives a real BackendSelector/
    // ServerBackend, which references OkHttp types in its internal (but androidTest-visible)
    // WebSocketFactory seam. `implementation(libs.okhttp)` above is main-only scope and does not
    // propagate to androidTest — this is the SAME pinned version, just also exposed to the test
    // compile classpath. Test-only; never touches the public SttEngine surface.
    androidTestImplementation(libs.okhttp)
}

// JitPack android-example publishing form. `from(components["release"])` MUST be inside
// afterEvaluate — the "release" software component does not exist at configuration time (it is
// created by the AGP singleVariant("release") opt-in above). groupId/version are what
// publishToMavenLocal writes; JitPack overrides groupId from the repo owner (com.github.Ygaray)
// and version from the resolved ref.
publishing {
    publications {
        register<MavenPublication>("release") {
            groupId = "com.github.Ygaray"
            // == the MIRROR REPO NAME, not the module name (:stt). Same rule the sibling follows:
            // its module is :backup and its artifactId is backup-engine.
            artifactId = "voice-engine-android"
            version = "0.3.1"
            afterEvaluate {
                from(components["release"])
            }
        }
    }
}
