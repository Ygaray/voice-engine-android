plugins {
    // Android LIBRARY (not application): no applicationId, no versionName, no Compose. The
    // append-only correction/corpus revision contract (Phase 12, CORPUS-01) — the FIFTH
    // independently published library module, zero :stt/:recorder/:voicenotes/:transcription
    // coupling.
    alias(libs.plugins.android.library)
    alias(libs.plugins.kotlin.android)
    // Same rationale as every sibling module (D-12): freezes this module's own public surface.
    // Provides :corrections:apiDump / :corrections:apiCheck.
    alias(libs.plugins.binary.compatibility.validator)
    `maven-publish`
}

android {
    // A distinct AGP namespace string, mirroring every sibling module's
    // io.github.ygaray.sttengine.<module-name> convention.
    namespace = "io.github.ygaray.sttengine.corrections"
    compileSdk = 36

    defaultConfig {
        minSdk = 33
        // No targetSdk / applicationId — a library inherits the consuming app's targetSdk.

        consumerProguardFiles("consumer-rules.pro")
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    testOptions {
        // Kept for build-shape consistency with every sibling module, even though :corrections'
        // tests need NEITHER Robolectric NOR these flags in practice — this module has zero I/O
        // and touches no Android platform API (a plain equality-contract data shape).
        unitTests.isIncludeAndroidResources = true
        unitTests.isReturnDefaultValues = true
    }

    // AGP-8 opt-in: declare the single publishable variant + its sources jar. MANDATORY —
    // without this, `from(components["release"])` below fails ("'release' property cannot be
    // found"), the #1 JitPack-Android publish failure.
    publishing {
        singleVariant("release") {
            withSourcesJar()
        }
    }
}

// ---------------------------------------------------------------------------------------------
// THE API FREEZE (mirrors :stt's/:recorder's/:voicenotes'/:transcription's, D-12).
//
// `api/corrections.api` is a golden dump of this module's RELEASE compilation, generated by
// :corrections:apiDump and diffed by :corrections:apiCheck. Any change to a public signature
// fails the build with a diff naming the symbol, instead of passing review unnoticed — this is
// the mechanical enforcement behind CORPUS-01's "no replace/update path" guarantee (T-12-02): a
// future contributor adding a mutation method becomes a loud, reviewed diff, never a silent one.
//
// The plugin already makes `check` depend on `apiCheck`. This declaration is deliberately explicit
// and redundant, same rationale as every sibling module: it makes the wiring load-bearing IN THIS
// FILE rather than an inherited plugin default.
tasks.named("check") {
    dependsOn(tasks.named("apiCheck"))
}

// TOP-LEVEL kotlin { } — a SIBLING of android { }, deliberately NOT nested inside it (mirrors
// every sibling module's Pitfall-9 warning: AGP's KotlinAndroidProjectExtension is a different
// receiver, and explicitApi() nested inside android {} would not do what is intended).
kotlin {
    explicitApi()
    compilerOptions {
        jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17)
    }
}

dependencies {
    // Zero runtime dependency (RESEARCH.md: "this phase adds no library dependency of any kind").
    // :corrections is a pure data shape with no suspend functions, no I/O — unlike :transcription
    // (coroutines/OkHttp) this module needs neither.
    testImplementation(libs.junit)
    // 13-05's fixture-driven CorrectionsTest reads the golden-vector JSON via org.json.JSONObject/
    // JSONArray. org.json.* is an Android-platform stub on the host JVM — without Robolectric,
    // AGP's unitTests.isReturnDefaultValues=true (set above) makes it silently return null/defaults
    // instead of really parsing. The real, standalone org.json:json JVM implementation (same
    // package/class names) is the standard Android-testing fix — test-only, never reaches the
    // release/runtime classpath. Mirrors :transcription's existing testImplementation(libs.json)
    // precedent.
    testImplementation(libs.json)
}

// JitPack android-example publishing form, mirrors every sibling module's exactly.
// `from(components["release"])` MUST be inside afterEvaluate — the "release" software component
// does not exist at configuration time (it is created by the AGP singleVariant("release") opt-in
// above).
publishing {
    publications {
        register<MavenPublication>("release") {
            groupId = "com.github.Ygaray"
            // Mirrors the sibling naming convention (module :transcription -> artifact
            // voice-engine-android-transcription): module :corrections -> artifact
            // voice-engine-android-corrections. NOT yet named in android/jitpack.yml — that is
            // Phase 17's job (REL-03, human-gated tag-cut); this publishing block is wired now so
            // the module's shape matches every sibling from its first commit.
            artifactId = "voice-engine-android-corrections"
            // Matches the version every other published module currently carries.
            version = "0.8.0"
            afterEvaluate {
                from(components["release"])
            }
        }
    }
}
